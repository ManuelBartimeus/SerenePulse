#!/usr/bin/env node
/* global process, console */
// Builds the survey island (one small IIFE bundle) and the logo into a generated module the Worker
// imports, so both are served from the Worker with content-hashed, immutable URLs.
// Runs from wrangler's [build] command (dev, deploy) and before typecheck/test.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..');
const out = path.join(app, 'dist', 'island');
const BUDGET_GZ = 35 * 1024; // PERFORMANCE_TARGETS: JS ≤ 35 KB gz

const result = await build({
  entryPoints: [path.join(app, 'island', 'main.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2019', // engine uses flatMap; Chrome 73+, Safari 12.1+
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
});
const js = result.outputFiles[0].text;
const logo = readFileSync(path.resolve(app, '../../packages/ui/assets/serene-logo.svg'), 'utf8');
const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);
const gz = gzipSync(js, { level: 9 }).length;

mkdirSync(out, { recursive: true });
writeFileSync(path.join(out, 'island.js'), js);
writeFileSync(
  path.join(out, 'assets.gen.ts'),
  `// Generated by scripts/build-island.mjs. Do not edit.\n` +
    `export const ISLAND_PATH = ${JSON.stringify(`/customerfeedback/assets/island.${hash(js)}.js`)};\n` +
    `export const ISLAND_JS = ${JSON.stringify(js)};\n` +
    `export const LOGO_PATH = ${JSON.stringify(`/customerfeedback/assets/logo.${hash(logo)}.svg`)};\n` +
    `export const LOGO_SVG = ${JSON.stringify(logo)};\n` +
    `export const ISLAND_GZ_BYTES = ${gz};\n`,
);
console.log(
  `island: ${js.length} B raw, ${gz} B gz (budget ${BUDGET_GZ}); logo ${logo.length} B raw, ${gzipSync(logo).length} B gz`,
);
if (gz > BUDGET_GZ) {
  console.error('island bundle is over the 35 KB gz budget');
  process.exit(1);
}
